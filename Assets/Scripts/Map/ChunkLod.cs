// 청크를 얼마나 자세히 구울지 나타내는 단계. 추적 대상에 가까운 청크는 Lod0, 그 바깥은 Lod1, 가장 먼 청크는 Lod2로 굽는다.
// 값이 작을수록 높은 품질이며, 이 순서를 비교해 청크를 올리거나 낮출지 정한다.
public enum ChunkLod
{
    // 풀과 자원을 소환하고 알파맵 바이옴 경계를 블러로 섞는 전체 품질
    Lod0,

    // 풀과 자원을 소환하지 않고 알파맵을 블러 없이 그대로 칠하는 원경용 품질
    Lod1,

    // LOD1처럼 풀과 자원이 없고, 알파맵도 아예 칠하지 않아 높이만 굽는 최원경용 품질
    Lod2,
}
